'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('index.html'),app=read('app.js'),dict=read('dictee-v2.js'),pet=read('pet-core.js'),styles=read('home-menus.css');
assert.match(html,/navigation\.js/);
assert.ok(html.indexOf('pet-core.js')<html.indexOf('app.js'),'Pet wallet initialized BEFORE 3-choice landing screen');
assert.ok(!html.includes('src="./rewards.js'),'Old 10/10-only modal no longer intercepts new all-round bonus');
for(const id of ['hub-math','hub-dictee','hub-pet'])assert.ok(app.includes('id="'+id+'"'),'Unique initial menu '+id);
for(const id of ['math-mixed','math-back'])assert.ok(app.includes(id));
assert.match(app,/Array\(4\)\.fill\(t\.id\)/,'20-question mixed math exam evenly covers five worlds');
assert.match(app,/Resultaat per wereld/,'Maths mixed exam includes per-world score');
assert.match(dict,/shuffle\(p\.words\)\.slice\(0,5\)/,'40-question mixed spelling exam evenly covers eight packs');
assert.match(dict,/Per woordpakket \/ By spelling pack/,'Spelling exam includes per-pack score');
assert.match(dict,/home3-earned/,'Dictee completion shows pet wallet reward');
assert.match(app,/home3-earned/,'Math completion shows pet wallet reward');
assert.match(app,/bonusCoins:25/,'Math sessions earn fixed completion bonus');
assert.match(dict,/bonusCoins:25/,'Dictation sessions earn fixed completion bonus');
assert.match(app,/window\.RekenArcade\?\.open/,'Finished maths always offers arcade');
assert.match(dict,/window\.RekenArcade\?window\.RekenArcade\.offerHTML/,'Finished dictation always offers arcade');
assert.match(app,/window\.RekenNavigation\?\.top\(\)/,'Math hub navigation scrolls to top');
assert.match(dict,/window\.RekenNavigation\?\.top\(\)/,'Dictee screen transitions scroll to top');
assert.match(read('pet-world.js'),/window\.RekenNavigation\?\.top\(\)/,'Pet rooms scroll to top');
for(const file of ['arcade-invaders.js','arcade-breakout.js','forest-game.js','pet-studio.js','memory-game.js']){
 assert.match(read(file),/window\.RekenNavigation\?\.top\(\)/,'Game opens at top on iPad: '+file);
}
assert.match(styles,/\.home3-grid/);
const idx=read('sw.js'),build=read('.github/workflows/deploy.yml');
for(const file of ['navigation.js','home-menus.css']){assert.ok(idx.includes(file));assert.ok(build.includes(file))}
const memory=new Map();
const storage={getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v))};
const window={};
const ctx={window,localStorage:storage,Math,JSON,Number,String,Array,Object,Set};
vm.runInNewContext(read('world-progress.js'),ctx);
vm.runInNewContext(pet,ctx);
const core=window.RekenPetCore;
const start=core.snapshot().coins;
assert.equal(start,60);
const mathData={history:[{topic:'blocks',correct:true}],sessions:[{mode:'practice',topic:'blocks',total:10,correct:8,bonusCoins:25}]};
memory.set('rekenreis-progress-v1',JSON.stringify(mathData));
assert.equal(core.snapshot().coins,60+5+25,'8/10 math completion gives answer coins and 25 reward');
mathData.sessions.push({mode:'exam',topic:'mixed',total:20,correct:12,bonusCoins:25});
memory.set('rekenreis-progress-v1',JSON.stringify(mathData));
const dictData={history:[{pack:2,correct:true}],sessions:[{mode:'short',pack:2,total:10,correct:8,bonusCoins:25}]};
memory.set('rekenreis-dictee-v1',JSON.stringify(dictData));
assert.equal(core.snapshot().coins,60+5+7+25*3,'Coins from both school subjects accumulate');
const balance=core.snapshot().coins;
core.snapshot();core.snapshot();
assert.equal(core.snapshot().coins,balance,'Viewing results does not award bonus twice');
mathData.sessions.push({mode:'practice',topic:'words',total:10,correct:10,date:'old'}); // historical reward absent
memory.set('rekenreis-progress-v1',JSON.stringify(mathData));
assert.equal(core.snapshot().coins,balance,'Old unmarked sessions not rewarded retroactively');
const h=memory.get('rekenreis-progress-v1'),d=memory.get('rekenreis-dictee-v1');
core.care('food');
assert.equal(memory.get('rekenreis-progress-v1'),h,'Pet activity never corrupts mathematics');
assert.equal(memory.get('rekenreis-dictee-v1'),d,'Pet activity never corrupts spelling');
console.log('PASS: 3 home menus, individual+mixed subjects, per-pack reporting, bonus coin economy and iPad scroll persistence.');
