'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const box={window:{}};
vm.runInNewContext(fs.readFileSync('spelling-coach.js','utf8'),box);
const coach=box.window.RekenSpellingCoach;
assert.ok(coach);
const testWord={word:'winkelen',phrase:'we winkelen',cue:'we',pack:7};
const r=coach.diagnose(testWord,'winklen');
assert.equal(r.distance,1,'Missing silent e diagnosed');
assert.match(r.html,/doffe e/);
assert.match(r.html,/coach-missing/);
assert.equal(coach.diagnose({word:'bakken',phrase:'zij bakken',cue:'zij',pack:2},'baken').distance,1);
assert.match(coach.diagnose({word:'bakken',phrase:'zij bakken',cue:'zij',pack:2},'baken').html,/twee medeklinkers/);
assert.equal(coach.diagnose(testWord,'we winkelen').distance,0,'Whole phrase accepted');
assert.equal(coach.diagnose({word:'glaasje',phrase:'het glaasje',cue:'het',pack:8},'glas je').distance>0,true);
const voiceCode=fs.readFileSync('voice-engine.js','utf8');
assert.match(voiceCode,/playbackRate/,'Slow pre-recorded audio playback');
assert.match(voiceCode,/nl-BE/,'Belgian Dutch requested');
assert.match(voiceCode,/speechSynthesis/,'Offline device fallback');
const dictCode=fs.readFileSync('dictee-v2.js','utf8');
assert.match(dictCode,/dict2-chunks/,'Chunked speaking UI');
assert.match(dictCode,/dict2-retry-form/,'Second spelling attempt UI');
assert.match(dictCode,/RekenLetterblaster.open/,'Retro spelling reward');
const studio=fs.readFileSync('pet-studio.js','utf8');
assert.match(studio,/studio-scrub/);
assert.match(studio,/studio-feed/);
assert.match(studio,/studio-sleep/);
assert.match(studio,/studio-arrow/);
console.log('PASS: individualized spelling, slow voice route, retries, Belgian voice priority and interactive pet care.');
