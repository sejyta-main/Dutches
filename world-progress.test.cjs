'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const window={};
vm.runInNewContext(fs.readFileSync('world-progress.js','utf8'),{window});
const progress=window.RekenWorldProgress;
const make=(topic,correct=10,mode='practice')=>({topic,mode,total:10,correct});
const state={history:[],sessions:[make('blocks'),make('place',9),make('words',10,'exam')]};
assert.deepEqual(Array.from(progress.mastered(state)),['blocks'],'Only a perfect individual world counts, not an exam or 9/10');
assert.equal(progress.isCompleted(state,'blocks'),true);
assert.equal(progress.isCompleted(state,'place'),false);
assert.deepEqual(Array.from(progress.remaining(state)),['place','words','line','compare']);
state.sessions.push(make('place'),make('words'),make('line'));
assert.deepEqual(Array.from(progress.mastered(state)),['blocks','place','words','line']);
assert.deepEqual(Array.from(progress.remember(state)),['blocks','place','words','line']);
assert.equal(state.masteredWorlds.length,4,'Permanent completed-world record');
state.sessions=[];assert.equal(progress.mastered(state).length,4,'Past success survives session-trimming and visits');
state.sessions.push(make('compare'));progress.remember(state);
assert.equal(progress.remaining(state).length,0,'All five worlds completed');
assert.deepEqual(Array.from(progress.mastered({sessions:[make('blocks',9),make('place',10,'exam')]})),[]);
const app=fs.readFileSync('app.js','utf8');
assert.ok(app.includes("worldProgress.isCompleted(data,id)"),'World guarded from direct start');
assert.ok(app.includes("done?'disabled aria-disabled="),'Disabled world button after mastery');
assert.ok(app.includes("worldProgress.remember(data)"),'Record completed worlds at round end');
assert.ok(app.includes("Volgende wereld"),'Next world action on summary');
const pet=fs.readFileSync('pet-world.js','utf8');
assert.ok(pet.includes("if(!c?.unlocked||c.mastered)return"),'Pet map cannot bypass a completed world');
assert.ok(pet.includes("window.RekenPetPlay.open"),'Pet mini-game integrated');
assert.ok(pet.includes("pet-pat"),'Pet can be petted');
assert.ok(pet.includes("pet-dance"),'Pet can dance');
const mini=fs.readFileSync('pet-play.js','utf8');
const box={};
vm.runInNewContext(mini,{window:box,document:{getElementById:()=>({})}});
assert.equal(typeof box.RekenPetPlay.open,'function','Pet interaction game available');
console.log('PASS: perfected worlds lock, next-world advance, persistent history, protected pet-map navigation, petting, dancing and ball play.');
